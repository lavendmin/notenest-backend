-- ============================================================================
-- NB1 권한 기본값 마이그레이션 — 가입 기본 역할 ROLE_ADMIN → ROLE_USER
--
-- 배경: 회원가입이 모든 사용자에게 ROLE_ADMIN 을 부여해 왔다(UserService.signUp).
--       코드는 NB1 에서 ROLE_USER 로 바꿨고, 이 스크립트는 이미 가입한 사용자를 정리한다.
--
-- 방식: 명시적 SQL(수동 적용). Flyway/Liquibase 미도입.
--
-- 전제: 현재 ROLE_ADMIN 은 전부 가입 기본값으로 부여된 것이며, 의도한 관리자 계정은 없다
--       (관리자 전용 기능 없음 — SecurityConfig 의 /admin 은 매핑된 컨트롤러가 없다).
--       실제 관리자로 남길 계정이 있다면 STEP 2 의 WHERE 에 해당 email 을 제외 조건으로 추가한다.
--
-- 참고: 이미 발급된 JWT 는 role 클레임을 담고 있어 만료(10시간)까지 옛 역할이 남는다.
--       관리자 전용 경로가 없으므로 실제 권한 차이는 없다.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- STEP 1. 현황 — 역할별 사용자 수
-- ----------------------------------------------------------------------------
SELECT role, COUNT(*) AS users FROM user GROUP BY role;

-- ----------------------------------------------------------------------------
-- STEP 2. 가입 기본값으로 부여된 ROLE_ADMIN 을 ROLE_USER 로 되돌린다
-- ----------------------------------------------------------------------------
UPDATE user SET role = 'ROLE_USER' WHERE role = 'ROLE_ADMIN';

-- ----------------------------------------------------------------------------
-- STEP 3. 검증 — ROLE_ADMIN 0건이어야 한다
-- ----------------------------------------------------------------------------
SELECT role, COUNT(*) AS users FROM user GROUP BY role;
